'use strict';

import Relaxy from '../../../src/Client/Relaxy.js';
import { Player } from '../../../src/Client/Modules/MusicPlayer/Player.js';

import {
    extractPlaylistId,
    personalListName,
    generatedListName
} from '../../../src/Client/Modules/MusicPlayer/extractors/youtubeUrls.js';

export default async (client, queue, tracks) => {
    const message = queue?.metadata;

    if (!message?.channel || !tracks?.length) {
        return;
    }

    const playlist = tracks.length > 1 ? tracks[0].playlist : null;
    const title = client.utils.firstLetterUp(playlist?.title ?? tracks[0].title);
    const requestedBy = tracks[0].requestedBy;

    const sanitizedServerName = client.utils.cstr(message.guild.name);
    const voiceChannel = message.member?.voice?.channel ?? 'Unavailable.';

    const listId = playlist?.url ? extractPlaylistId(playlist.url) : null;

    const personal = personalListName(listId);
    const generated = generatedListName(listId);

    const origin = personal
        ? `\n-# From a **private playlist** (${personal}) - these are the tracks on **Relaxy's** account, not yours.`
        : generated
          ? `\n-# From ${generated} - auto-generated by YouTube rather than a curated playlist.`
          : '';

    const description = `Server: **${sanitizedServerName}**\nChannel: **${voiceChannel}**\nRequested by: **${requestedBy ?? 'Unavailable.'}**${origin}`;

    return client.send(message.channel, null, {
        default: [
            {
                color: client.data.embedColor,
                title,
                url: playlist?.url ?? tracks[0].url,
                thumbnail: {
                    url: client.utils.trackThumbnail(tracks[0])
                },
                author: {
                    name:
                        tracks.length > 1
                            ? `${tracks.length} songs have been added to the queue!`
                            : 'Added to the queue:',
                    icon_url: client.config.text.links.musicImage
                },
                description
            }
        ],
        alternate: `## Added\n${title}${tracks.length > 1 ? ` - ${tracks.length} songs` : ''}\n${description}`
    });
};
