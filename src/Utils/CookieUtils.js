'use strict';
export const YT_COOKIE_DOMAINS = Object.freeze([
    'youtube.com',
    '.youtube.com',
    'google.com',
    '.google.com',
    'accounts.google.com'
]);

export const parseNetscapeCookies = body =>
{
    const pairs = [];
    const seen = new Set();

    for (const rawLine of String(body).split(/\r?\n/))
    {
        const line = rawLine.trimEnd();

        if (!line || (line.startsWith('#') && !line.startsWith('#HttpOnly_')))
        {
            continue;
        }

        const cols = line.replace(/^#HttpOnly_/, '').split('\t');
        if (cols.length < 7)
        {
            continue;
        }

        const domain = cols[0].trim();
        const name = cols[5].trim();
        const value = cols[6].trim();
        if (!name)
        {
            continue;
        }

        const domainMatches = YT_COOKIE_DOMAINS.some(d => domain === d || domain.endsWith(d));
        if (!domainMatches || seen.has(name))
        {
            continue;
        }

        seen.add(name);
        pairs.push(`${name}=${value}`);
    }

    return pairs.length
        ? pairs.join('; ')
        : null;
};

export const normalizeCookieValue = value =>
{
    if (!value || typeof value !== 'string')
    {
        return null;
    }

    if (value.includes('\t'))
    {
        return parseNetscapeCookies(value);
    }

    const trimmed = value.trim();
    return trimmed || null;
};
export const countCookies = header =>
{
    const normalized = normalizeCookieValue(header);
    return normalized
        ? normalized.split('; ').filter(Boolean).length
        : 0;
};

export const headerToNetscape = value =>
{
    const header = normalizeCookieValue(value);
    if (!header)
    {
        return null;
    }

    const expiry = Math.floor(Date.now() / 1000) + (60 * 60 * 24 * 365 * 10);
    const lines = [
        '# Netscape HTTP Cookie File',
        '# Generated by Relaxy'
    ];

    for (const pair of header.split('; '))
    {
        const idx = pair.indexOf('=');
        if (idx < 1)
        {
            continue;
        }
        const name = pair.slice(0, idx);
        const val = pair.slice(idx + 1);
        lines.push([
            '.youtube.com',
            'TRUE',
            '/',
            'TRUE',
            String(expiry),
            name,
            val
        ].join('\t'));
    }

    return lines.length > 2
        ? lines.join('\n') + '\n'
        : null;
};
